// Declaración de un objeto literal con tipos inferidos
const persona = {
  nombre: 'Lucía',
  edad: 22,
  ciudad: 'Valencia',
  esEstudiante: true
};

console.log(`Nombre: ${persona.nombre}`);
console.log(`Edad: ${persona.edad}`);
console.log(`Ciudad: ${persona.ciudad}`);
console.log(`¿Es estudiante?: ${persona.esEstudiante ? 'Sí' : 'No'}`);